import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { execFileSync } from 'node:child_process';
import { PUBLIC_STATIC_ROUTES, PUBLIC_DYNAMIC_ROUTE_TEMPLATES } from '../public-route-registry.mjs';
const web = resolve(import.meta.dirname, '..');
const app = resolve(web, 'src/app');
const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? walk(resolve(dir, entry.name))
      : entry.name === 'page.tsx'
        ? [resolve(dir, entry.name)]
        : []
  );
const files = walk(app).map((file) => ({
  file,
  route: '/' + relative(app, file).replace(/(?:^|\/)page\.tsx$/, ''),
}));
const shape = (path) => path.replace(/\{[^}]+\}|\[[^\]]+\]/g, '{}').replace(/\/$/, '');
const resolvePage = (route) => {
  const file = files.find((file) => shape(file.route) === shape(route));
  if (!file) throw new Error(`Public renderer has no authored page: ${route}`);
  return file;
};
const statics = PUBLIC_STATIC_ROUTES.map((entry, index) => ({
  ...entry,
  index,
  source: resolvePage(entry.path),
}));
const dynamic = PUBLIC_DYNAMIC_ROUTE_TEMPLATES.map((entry, index) => ({
  ...entry,
  index,
  source: resolvePage(entry.html),
}));
let output = `// Generated by scripts/build-public-source-registry.mjs from public-route-registry.mjs.\nimport type { Metadata } from 'next';\nimport { publicRouteDescriptor } from '../../public-route-registry.mjs';\n`;
for (const item of statics)
  output += `import * as page${item.index} from '@/app/${relative(app, item.source.file).replace(/\.tsx$/, '')}';\n`;
for (const item of dynamic)
  output += `import * as dynamic${item.index} from '@/app/${relative(app, item.source.file).replace(/\.tsx$/, '')}';\n`;
output += `type PublicPage = { default: (props: any) => unknown; metadata?: Metadata; generateStaticParams?: () => Array<Record<string, string>>; generateMetadata?: (props: any) => Promise<Metadata> | Metadata };\nconst pages: Record<string, PublicPage> = {\n`;
for (const item of statics) output += `${JSON.stringify(item.path)}: page${item.index},\n`;
output += `};\nconst families: Record<string, { page: PublicPage; keys: string[] }> = {\n`;
for (const item of dynamic) {
  const metadata = item.metadataFrom
    ? dynamic.find((route) => route.id === item.metadataFrom)
    : null;
  if (item.metadataFrom && !metadata)
    throw new Error(`Unknown metadata source: ${item.metadataFrom}`);
  const page = metadata
    ? `{ ...dynamic${item.index}, generateMetadata: dynamic${metadata.index}.generateMetadata }`
    : `dynamic${item.index}`;
  const keys = [...item.source.route.matchAll(/\[([^\]]+)\]/g)].map((match) => match[1]);
  output += `${JSON.stringify(item.id)}: {page: ${page}, keys: ${JSON.stringify(keys)}},\n`;
}
output += `};\nexport function publicSourcePage(path: string) {\nif (pages[path]) return {page: pages[path]!, props: {params: Promise.resolve({}), searchParams: Promise.resolve({})}};\nconst descriptor = publicRouteDescriptor(path);\nconst selected = descriptor?.type === 'dynamic' ? families[descriptor.route.id] : null;\nif (!selected) return null;\nconst values = path.split('/').filter(Boolean).slice(-selected.keys.length);\nconst params = Object.fromEntries(selected.keys.map((key, index) => [key, values[index]]));\nreturn {page: selected.page, props: {params: Promise.resolve(params), searchParams: Promise.resolve({})}};\n}\n`;
const target = resolve(web, 'src/lib/public-source-pages.ts');
output = execFileSync('pnpm', ['exec', 'biome', 'format', '--stdin-file-path', target], {
  cwd: resolve(web, '../..'),
  input: output,
  encoding: 'utf8',
});
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Public source registry is stale; run the build script.');
} else writeFileSync(target, output);
console.log(
  `Public source registry: ${statics.length} static pages and ${dynamic.length} dynamic families.`
);
